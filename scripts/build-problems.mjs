/**
 * Builds data/problems/extra.js from scripts/problem-sources/extra-problems.mjs:
 * runs each reference solution (our own code, locally with Node) on every
 * sample and hidden input and records the output as the expected answer.
 *
 *   npm run build:problems    (then npm test re-verifies everything)
 */
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { EXTRA_PROBLEMS } from "./problem-sources/extra-problems.mjs";

const norm = (s) => String(s ?? "").replace(/\r\n/g, "\n").split("\n").map((l) => l.replace(/\s+$/, "")).join("\n").replace(/\n+$/, "");

function solve(p, input) {
  const run = spawnSync(process.execPath, ["-e", p.ref], { input, encoding: "utf8", timeout: 5000 });
  if (run.status !== 0) throw new Error(`${p.slug}: reference failed on ${JSON.stringify(input)}\n${run.stderr}`);
  const out = norm(run.stdout);
  if (out === "") throw new Error(`${p.slug}: empty output for ${JSON.stringify(input)}`);
  return out;
}

const built = EXTRA_PROBLEMS.map(({ ref: _ref, hidden, samples, ...p }) => ({
  ...p,
  samples: samples.map((s) => ({ input: s.input, output: solve({ ...p, ref: _ref }, s.input), explanation: s.explanation })),
  hiddenTests: hidden.map((input) => ({ input, output: solve({ ...p, ref: _ref }, input) })),
}));

const header = `/**
 * Second batch of AlgoArena problems: original statements in the LeetCode /
 * Codeforces style. GENERATED by scripts/build-problems.mjs from
 * scripts/problem-sources/extra-problems.mjs: edit the source, not this file.
 * Expected outputs come from running each reference solution.
 */
`;
writeFileSync("data/problems/extra.js", `${header}export const EXTRA_RAW = ${JSON.stringify(built, null, 2)};\n`);
console.log(`Wrote data/problems/extra.js: ${built.length} problems, ${built.reduce((s, p) => s + p.samples.length + p.hiddenTests.length, 0)} tests.`);
